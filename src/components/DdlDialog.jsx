import { useMemo, useState } from 'react';
import Modal from './Modal.jsx';
import { dialectFor, dialectName, generateDdl } from '../lib/ddl.js';

/** Shows CREATE TABLE statements for proposed entities, to copy or download. */
export default function DdlDialog({ source, scope, model, saved, only = null, title, onClose }) {
  const [ifNotExists, setIfNotExists] = useState(true);
  const [copied, setCopied] = useState(false);

  const sql = useMemo(() => {
    const header = [
      saved ? `Data model: ${saved.name} (version ${saved.version})` : `Unsaved data model for ${scope}`,
      `Generated by ERD Explorer on ${new Date().toISOString().slice(0, 10)}`,
    ];
    return generateDdl(model, { source, only, ifNotExists, header });
  }, [model, source, scope, saved, only, ifNotExists]);

  const count = (model?.tables ?? []).filter((t) => t.proposed && (!only || only.includes(t.id))).length;
  const fileName = `${(saved?.name ?? scope).replace(/[^\w.-]+/g, '_')}${only?.length === 1 ? `_${model.tables.find((t) => t.id === only[0])?.name}` : ''}.sql`;

  const copy = async () => {
    await navigator.clipboard.writeText(sql);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  };

  const download = () => {
    const url = URL.createObjectURL(new Blob([sql], { type: 'application/sql' }));
    Object.assign(document.createElement('a'), { href: url, download: fileName }).click();
    URL.revokeObjectURL(url);
  };

  return (
    <Modal
      title={title ?? 'DDL for proposed entities'}
      subtitle={`${count} table${count === 1 ? '' : 's'} · ${dialectName(dialectFor(source))}`}
      onClose={onClose}
      wide
      footer={
        <>
          <label className="check muted">
            <input type="checkbox" checked={ifNotExists} onChange={(e) => setIfNotExists(e.target.checked)} />
            IF NOT EXISTS
          </label>
          <button className="btn" onClick={copy}>{copied ? 'Copied' : 'Copy'}</button>
          <button className="btn primary" onClick={download}>Download .sql</button>
        </>
      }
    >
      <p className="muted small">
        Nothing is run from here. Run the script in {source === 'lakebase' ? 'a Postgres client or the Lakebase SQL editor' : 'the Databricks SQL editor or a notebook'}{' '}
        with an identity that can create tables in {scope}. Foreign keys are added after all the tables are created
        {source === 'lakebase' ? '' : '; in Unity Catalog they are informational and not enforced'}.
      </p>
      <pre className="ddl">{sql}</pre>
    </Modal>
  );
}
